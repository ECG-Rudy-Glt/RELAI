#!/usr/bin/env python3
"""Prototype of `relai handoff`: build a compact, deterministic "where are we" file for a repo.

Reads only local, structured sources (no LLM): git, Beads (`bd --json`), OpenSpec
(`openspec list --json`) and an optional hand-curated `.relai/notes.md` (decisions, pitfalls).
Writes Markdown to stdout. Budget is enforced by truncating lists, never by summarising.

Usage: handoff.py [repo_path] [--max-tasks N] [--max-commits N]
"""
import argparse
import json
import os
import shutil
import subprocess
import sys


def run(cmd, cwd):
    try:
        out = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=60)
        return out.stdout if out.returncode == 0 else ""
    except (OSError, subprocess.TimeoutExpired):
        return ""


def as_json(text, default):
    try:
        return json.loads(text) if text.strip() else default
    except json.JSONDecodeError:
        return default


def git_section(repo, max_commits):
    branch = run(["git", "branch", "--show-current"], repo).strip() or "?"
    head = run(["git", "log", "-1", "--format=%h %cs"], repo).strip()
    log = run(["git", "log", f"-{max_commits}", "--format=- %h %cs %s"], repo).rstrip()
    dirty = [l for l in run(["git", "status", "--short"], repo).splitlines() if l.strip()]
    lines = [f"Branch `{branch}` at {head}. Uncommitted files: {len(dirty)}."]
    if dirty:
        lines += [f"  - `{l[3:]}`" for l in dirty[:10]] + (["  - …"] if len(dirty) > 10 else [])
    lines += ["", "Recent commits:", log or "- (none)"]
    return lines


def short(text, n=110):
    text = " ".join((text or "").split())
    return text if len(text) <= n else text[: n - 1] + "…"


def tasks_section(repo, max_tasks):
    if not shutil.which("bd") or not os.path.isdir(os.path.join(repo, ".beads")):
        return ["(no Beads task graph in this repo)"]
    ready = as_json(run(["bd", "ready", "--json"], repo), [])
    doing = as_json(run(["bd", "list", "--status", "in_progress", "--json"], repo), [])
    lines = []
    if doing:
        lines.append("In progress:")
        lines += [f"- `{t['id']}` P{t.get('priority', '?')} {short(t['title'])}" for t in doing[:max_tasks]]
    lines.append(f"Ready (unblocked, {len(ready)} total, top {min(len(ready), max_tasks)}):")
    lines += [f"- `{t['id']}` P{t.get('priority', '?')} {short(t['title'])}" for t in ready[:max_tasks]]
    lines.append("Details: `bd show <id>`.")
    return lines


def specs_section(repo):
    if not shutil.which("openspec") or not os.path.isdir(os.path.join(repo, "openspec")):
        return ["(no OpenSpec changes in this repo)"]
    data = as_json(run(["openspec", "list", "--json"], repo), {})
    changes = data.get("changes", []) if isinstance(data, dict) else []
    if not changes:
        return ["No active change."]
    return [f"- `{c['name']}` {c.get('completedTasks', 0)}/{c.get('totalTasks', 0)} tasks ({c.get('status', '?')})"
            for c in changes] + ["Details: `openspec show <name>`."]


def notes_section(repo):
    path = os.path.join(repo, ".relai", "notes.md")
    if not os.path.exists(path):
        return ["(no `.relai/notes.md`: decisions and pitfalls are not curated yet)"]
    return open(path, encoding="utf-8").read().rstrip().splitlines()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("repo", nargs="?", default=".")
    ap.add_argument("--max-tasks", type=int, default=8)
    ap.add_argument("--max-commits", type=int, default=8)
    a = ap.parse_args()
    repo = os.path.abspath(a.repo)
    out = [f"# Handoff — {os.path.basename(repo)}", "",
           "Generated by `relai handoff` (prototype). Read this, then `bd ready`; load anything else on demand.", "",
           "## State", *git_section(repo, a.max_commits), "",
           "## Tasks", *tasks_section(repo, a.max_tasks), "",
           "## Active changes (specs)", *specs_section(repo), "",
           "## Decisions and pitfalls", *notes_section(repo), ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
