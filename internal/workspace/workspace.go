// Package workspace builds one short, deterministic overview of all the projects of an index: what
// each is, how recently it moved, what tasks are open and what it provides. It is the cross-project
// counterpart of the per-repository handoff, for an agent that needs to know where to go before it
// opens any repository.
//
// It reads only files: each project's relai.yaml (through the index), `.beads/issues.jsonl` (the copy
// of the task list that lives in git) and the date of the last commit. It never runs bd, which would
// rewrite its database for every project on every call.
package workspace

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"unicode/utf8"

	"github.com/ECG-Rudy-Glt/RELAI/internal/handoff"
	"github.com/ECG-Rudy-Glt/RELAI/internal/index"
)

// FormatVersion is the version of the workspace overview format.
const FormatVersion = "0.1"

// Project is what is known about one indexed repository.
type Project struct {
	ID, Summary, Source string
	LastCommit          string // YYYY-MM-DD, "" when unknown
	Provides            []string
	Open, Doing         int
	Top                 []handoff.TaskBrief // most urgent unfinished tasks
	Remote              bool                // a clone URL: not read here
	NoTaskList          bool                // no .beads/issues.jsonl: "no list" is not "no tasks"
}

// Options controls the overview.
type Options struct {
	MaxTokens int
}

// DefaultOptions keeps the overview small enough to read at the start of every session.
func DefaultOptions() Options { return Options{MaxTokens: 800} }

// Load reads the projects of the index entries.
func Load(entries []index.Entry) []Project {
	var out []Project
	for _, e := range entries {
		p := Project{ID: e.RelaiYAML.ID, Summary: e.RelaiYAML.Summary, Source: e.Source}
		if p.ID == "" {
			p.ID = e.Source
		}
		for _, c := range e.RelaiYAML.Provides {
			p.Provides = append(p.Provides, c.Capability)
		}
		if strings.Contains(e.Source, "://") || strings.HasPrefix(e.Source, "git@") {
			p.Remote = true
			out = append(out, p)
			continue
		}
		if o, err := exec.Command("git", "-C", e.Source, "log", "-1", "--format=%cs").Output(); err == nil {
			p.LastCommit = strings.TrimSpace(string(o))
		}
		if _, err := os.Stat(filepath.Join(e.Source, ".beads", "issues.jsonl")); err != nil {
			p.NoTaskList = true
		}
		tasks := handoff.SnapshotBrief(e.Source)
		for _, t := range tasks {
			if t.Status == "in_progress" {
				p.Doing++
			} else {
				p.Open++
			}
		}
		if len(tasks) > 3 {
			tasks = tasks[:3]
		}
		p.Top = tasks
		out = append(out, p)
	}
	// Most recently active first; ties and unknown dates by id, so the output never depends on the
	// order of the index.
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].LastCommit != out[j].LastCommit {
			return out[i].LastCommit > out[j].LastCommit
		}
		return out[i].ID < out[j].ID
	})
	return out
}

// Render writes the overview within the token budget. The budget is met by showing fewer tasks per
// project first, then fewer capabilities, then listing the least recently active projects by name
// only, then only counting them; it never rewords.
func Render(projects []Project, o Options) string {
	if o.MaxTokens <= 0 {
		o = DefaultOptions()
	}
	// Each step is a (tasks per project, projects shown in full, capabilities per project).
	type level struct{ tasks, full, caps int }
	n := len(projects)
	var levels []level
	for _, t := range []int{3, 2, 1, 0} {
		levels = append(levels, level{t, n, 6})
	}
	for _, c := range []int{3, 0} {
		levels = append(levels, level{0, n, c})
	}
	for full := n - 1; full >= 0; full-- {
		levels = append(levels, level{0, full, 0})
	}
	levels = append(levels, level{0, -1, 0}) // names omitted too: only the count
	var doc string
	for _, l := range levels {
		doc = render(projects, l.tasks, l.full, l.caps)
		if handoff.EstimateTokens(doc) <= o.MaxTokens {
			return doc
		}
	}
	return doc
}

func render(ps []Project, tasks, full, caps int) string {
	namesOmitted := full < 0
	if namesOmitted {
		full = 0
	}
	var b strings.Builder
	p := func(f string, a ...any) { b.WriteString(clean(fmt.Sprintf(f, a...)) + "\n") }
	p("# Workspace — %d projects", len(ps))
	p("")
	p("Generated by `relai workspace` (format v%s). Task counts come from each project's `.beads/issues.jsonl` copy and may lag the live list; open a project's own handoff (`relai handoff <dir>`) before working in it.", FormatVersion)
	p("")
	if len(ps) == 0 {
		p("(the index is empty: build it with `relai index build`)")
		return b.String()
	}
	var rest []Project
	for i, pr := range ps {
		if i >= full {
			rest = append(rest, pr)
			continue
		}
		line := fmt.Sprintf("- `%s`", pr.ID)
		switch {
		case pr.Remote:
			line += " (remote, not read here)"
		case pr.LastCommit != "":
			line += " — last commit " + pr.LastCommit
		}
		if pr.Summary != "" {
			line += " — " + short(pr.Summary, 80)
		}
		p("%s", line)
		var facts []string
		switch {
		case pr.Remote:
		case pr.NoTaskList:
			facts = append(facts, "no task list in git (unknown, not zero)")
		default:
			facts = append(facts, fmt.Sprintf("%d open, %d in progress", pr.Open, pr.Doing))
		}
		if caps > 0 && len(pr.Provides) > 0 {
			shown := pr.Provides
			if len(shown) > caps {
				shown = shown[:caps]
			}
			s := "provides " + strings.Join(shown, ", ")
			if len(pr.Provides) > caps {
				s += fmt.Sprintf(" (+%d)", len(pr.Provides)-caps)
			}
			facts = append(facts, s)
		}
		if len(facts) > 0 {
			p("  %s", strings.Join(facts, " · "))
		}
		for i, t := range pr.Top {
			if i == tasks {
				break
			}
			p("  - `%s` P%d %s", t.ID, t.Priority, short(t.Title, 70))
		}
	}
	if len(rest) > 0 {
		p("")
		p("## Not shown in full (%d, least recently active)", len(rest))
		if namesOmitted {
			p("(names left out to stay within the budget: run `relai find` or `relai workspace --max-tokens` with a larger budget)")
		} else {
			var ids []string
			for _, r := range rest {
				ids = append(ids, r.ID)
			}
			p("%s", strings.Join(ids, ", "))
		}
	}
	return b.String()
}

func short(s string, n int) string {
	s = strings.Join(strings.Fields(s), " ")
	if utf8.RuneCountInString(s) <= n {
		return s
	}
	return string([]rune(s)[:n-1]) + "…"
}

// clean drops control characters from text that comes from other projects' files.
func clean(s string) string {
	return strings.Map(func(r rune) rune {
		if (r < 0x20 && r != '\n' && r != '\t') || r == 0x7f {
			return -1
		}
		return r
	}, s)
}
